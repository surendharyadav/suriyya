import pandas as pd
import numpy as np
from scipy import stats
from sklearn.ensemble import IsolationForest
import json
from typing import Dict, List, Tuple

class MetricsAnalyzer:
    def __init__(self, dashboard_path: str):
        self.df = pd.read_csv(dashboard_path)
        self.df['date'] = pd.to_datetime(self.df['date'])
        self.baseline_period = self.df[self.df['day'] == 'Pre-launch']
        self.launch_period = self.df[self.df['day'] != 'Pre-launch']

    def detect_anomalies(self, metric: str, window: int = 7) -> Dict:
        """Detect anomalies using Isolation Forest"""
        values = self.df[metric].values.reshape(-1, 1)
        iso_forest = IsolationForest(contamination=0.1, random_state=42)
        anomalies = iso_forest.fit_predict(values)

        anomaly_dates = self.df[anomalies == -1]['date'].dt.date.tolist()
        return {
            'metric': metric,
            'anomaly_dates': anomaly_dates,
            'severity': 'HIGH' if len(anomaly_dates) > 2 else 'MEDIUM'
        }

    def calculate_trend_changes(self) -> Dict[str, Dict]:
        """Calculate percentage change from baseline to launch period"""
        trends = {}
        for metric in ['dau', 'd1_retention', 'crash_rate', 'api_latency_p95',
                      'payment_success_rate', 'feature_adoption']:
            baseline_mean = self.baseline_period[metric].mean()
            launch_mean = self.launch_period[metric].mean()
            change_pct = ((launch_mean - baseline_mean) / baseline_mean) * 100

            trends[metric] = {
                'baseline': baseline_mean,
                'launch': launch_mean,
                'change_pct': round(change_pct, 2),
                'direction': 'DOWN' if change_pct < 0 else 'UP',
                'concerning': change_pct < -5 or (metric == 'crash_rate' and change_pct > 20)
            }
        return trends

    def get_key_metrics_summary(self) -> Dict:
        """Get critical metrics at a glance"""
        latest = self.df.iloc[-1]
        return {
            'latest_dau': latest['dau'],
            'dau_change_pct': round((latest['dau'] - self.baseline_period['dau'].mean()) /
                                  self.baseline_period['dau'].mean() * 100, 1),
            'crash_rate': latest['crash_rate'],
            'latency_p95': latest['api_latency_p95'],
            'payment_success': latest['payment_success_rate'],
            'support_tickets': latest['support_tickets'],
            'feature_adoption': latest['feature_adoption']
        }



