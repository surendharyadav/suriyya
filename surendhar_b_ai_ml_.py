class DataAnalystAgent:
    def __init__(self):
        pass

    def comprehensive_analysis(self, metrics_tool: MetricsAnalyzer,
                            sentiment_tool: SentimentAnalyzer) -> Dict:
        """Full quantitative analysis with statistical significance"""
        trends = metrics_tool.calculate_trend_changes()
        anomalies = [metrics_tool.detect_anomalies(metric) for metric in
                    ['crash_rate', 'api_latency_p95', 'dau']]
        sentiment = sentiment_tool.analyze_sentiment()
        key_metrics = metrics_tool.get_key_metrics_summary()

        # Statistical significance test
        p_values = {}
        for metric in ['dau', 'd1_retention', 'crash_rate']:
            baseline = metrics_tool.baseline_period[metric]
            launch = metrics_tool.launch_period[metric]
            t_stat, p_val = stats.ttest_ind(launch, baseline)
            p_values[metric] = round(p_val, 4)

        confidence = self._calculate_confidence(p_values, sentiment, anomalies)

        return {
            'trends': trends,
            'anomalies': anomalies,
            'sentiment': sentiment,
            'statistical_significance': p_values,
            'confidence_score': confidence,
            'key_takeaways': self._generate_takeaways(trends, sentiment, anomalies)
        }

    def _calculate_confidence(self, p_values: Dict, sentiment: Dict,
                            anomalies: List) -> float:
        sig_changes = sum(1 for p in p_values.values() if p < 0.05)
        anomaly_severity = sum(1 for a in anomalies if a['severity'] == 'HIGH')
        sentiment_impact = 1 if sentiment['overall_score'] < -0.2 else 0.5

        return max(0, 100 - (sig_changes * 20 + anomaly_severity * 15 + sentiment_impact * 20))

    def _generate_takeaways(self, trends: Dict, sentiment: Dict, anomalies: List) -> List[str]:
        takeaways = []
        concerning_metrics = [k for k, v in trends.items() if v['concerning']]
        if concerning_metrics:
            takeaways.append(f"Concerning metrics: {', '.join(concerning_metrics)}")
        if sentiment['negative_ratio'] > 0.4:
            takeaways.append("High negative sentiment detected")
        return takeaways





