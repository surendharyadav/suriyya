from vaderSentiment.vaderSentiment import SentimentIntensityAnalyzer
import json
import re
from collections import Counter
from typing import Dict, List

class SentimentAnalyzer:
    def __init__(self, feedback_path: str):
        with open(feedback_path, 'r') as f:
            self.feedback = json.load(f)
        self.analyzer = SentimentIntensityAnalyzer()

    def analyze_sentiment(self) -> Dict:
        """Analyze sentiment across all feedback"""
        sentiments = []
        keywords = []

        for feedback in self.feedback:
            score = self.analyzer.polarity_scores(feedback)
            sentiments.append(score)

            # Extract keywords
            words = re.findall(r'\b\w+\b', feedback.lower())
            keywords.extend([w for w in words if len(w) > 3])

        avg_sentiment = sum(s['compound'] for s in sentiments) / len(sentiments)

        keyword_counts = Counter(keywords).most_common(10)

        return {
            'overall_score': round(avg_sentiment, 3),
            'sentiment_category': self._categorize_sentiment(avg_sentiment),
            'positive_ratio': len([s for s in sentiments if s['compound'] > 0.05]) / len(sentiments),
            'negative_ratio': len([s for s in sentiments if s['compound'] < -0.05]) / len(sentiments),
            'top_keywords': keyword_counts,
            'sentiment_trend': 'DETERIORATING' if avg_sentiment < -0.1 else 'STABLE'
        }

    def _categorize_sentiment(self, score: float) -> str:
        if score >= 0.05:
            return "POSITIVE"
        elif score <= -0.05:
            return "NEGATIVE"
        else:
            return "NEUTRAL"



